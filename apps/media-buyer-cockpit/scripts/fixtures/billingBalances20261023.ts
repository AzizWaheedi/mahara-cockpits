/** A deep copy, so a test can change a fixture without touching another. */
export function copyRead(read: BalancesRead): BalancesRead {
  return JSON.parse(JSON.stringify(read)) as BalancesRead;
}

/**
 * The list after Aziz's ties (PLAN 6.4, 1 to 3): the three Tap charges of
 * شركة العلا and Marble's 13 Aug Tap charge tied to their deals (they join
 * the deal ledger and leave the untied list), and the deal اكتوروس للتشيد
 * linked to Arcturus Construction with its Whop payer tied to the deal.
 */
export function afterTies(read: BalancesRead): BalancesRead {
  const out = copyRead(read);
  const card = (name: string) => {
    const c = out.cards.find(x => x.name === name);
    if (!c) throw new Error(`no card ${name}`);
    return c;
  };
  const dealOf = (taskId: string) => {
    const d = out.deals.find(x => x.taskId === taskId);
    if (!d) throw new Error(`no deal for ${taskId}`);
    return d;
  };
  const tie = (paymentId: string, dealResponseId: string) => {
    const u = out.untied.find(x => x.id === paymentId) as
      | ReadUntied
      | undefined;
    if (!u) throw new Error(`no untied payment ${paymentId}`);
    out.untied = out.untied.filter(x => x.id !== paymentId);
    const rail: ReadRail = {
      dealResponseId,
      paymentId,
      day: u.day,
      usd: u.usd,
      rail: u.rail,
      kind: "remainder",
      fromLedger: true,
      byHand: false,
    };
    out.rails.push(rail);
    return rail;
  };
  const ola = dealOf(card("شركة العلا").taskId).responseId;
  for (const id of out.untied
    .filter(
      u =>
        u.rail === "tap" &&
        ["2026-08-30", "2026-09-02", "2026-10-20"].includes(u.day),
    )
    .map(u => u.id))
    tie(id, ola);
  const marble = dealOf(card("Marble and more").taskId).responseId;
  for (const id of out.untied
    .filter(u => u.rail === "tap" && u.day === "2026-08-13")
    .map(u => u.id))
    tie(id, marble);
  const arcturus = card("Arcturus Construction");
  const unlinked = out.unlinked.find(
    u => u.suggestedTaskId === arcturus.taskId,
  );
  if (!unlinked) throw new Error("no unlinked deal for Arcturus");
  out.unlinked = out.unlinked.filter(u => u !== unlinked);
  const {
    suggestedTaskId: _s,
    suggestedName: _n,
    suggestedSignupOn: _o,
    rails: _r,
    ...deal
  } = unlinked;
  out.deals.push({
    ...deal,
    taskId: arcturus.taskId,
    matchedBy: "link",
    linkedByName: "Abdulaziz Waheedi",
    conflict: false,
    otherForms: [],
  });
  for (const id of out.untied
    .filter(
      u =>
        u.rail === "whop" &&
        ((u.day === "2026-08-24" && u.usd === 500) ||
          (u.day === "2026-09-01" && u.usd === 1500)),
    )
    .map(u => u.id))
    tie(id, deal.responseId);
  return out;
}


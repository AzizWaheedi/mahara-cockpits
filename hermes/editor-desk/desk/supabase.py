def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _q(value: str) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


class SupabaseError(Exception):
    pass


class RpcError(SupabaseError):
    """A database function refused, with PostgREST's own fields: `sqlstate`
    (its `code`: a SQLSTATE such as 40001, or PGRST202 for a function that
    does not exist), `message` (the sentence) and `hint` (the code name the
    decks' functions put there)."""

    def __init__(self, sqlstate: str, message: str, hint: Optional[str] = None, status: int = 0):
        self.sqlstate = sqlstate
        self.message = message
        self.hint = hint
        self.status = status
        super().__init__(http.scrub(f"{sqlstate}: {message}" + (f" ({hint})" if hint else "")))


def rpc_error(e: http.HttpError) -> Optional[RpcError]:
    """PostgREST's JSON error as an RpcError, or None when the body is not one."""
    try:
        data = json.loads((e.body or b"").decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        return None
    if not isinstance(data, dict) or not data.get("code") or "message" not in data:
        return None
    hint = data.get("hint")
    return RpcError(str(data["code"]), str(data.get("message") or ""), str(hint) if hint else None, e.status)


class StorageTooLarge(http.HttpError):
    """Storage refused an upload for its size (413, or a 400 that says so)."""


# The test the browser keeps as `tooLarge` in src/present/sources.ts.
_TOO_LARGE_RE = re.compile(r"maximum allowed size|payload too large|entity too large|exceeded", re.I)
UPLOAD_CHUNK = 1 << 20


def _storage_duplicate(status: int, body: bytes) -> bool:
    """Storage answers an existing object as HTTP 409, or as a 400 whose JSON
    says statusCode "409" or error "Duplicate", depending on its version."""
    if status == 409:
        return True
    try:
        data = json.loads(body.decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        return False
    return isinstance(data, dict) and (str(data.get("statusCode") or "") == "409" or data.get("error") == "Duplicate")


def _storage_too_large(status: int, body: bytes) -> bool:
    return status == 413 or (status == 400 and bool(_TOO_LARGE_RE.search(body.decode("utf-8", "replace"))))


def _is_timeout(e: BaseException) -> bool:
    if isinstance(e, (socket.timeout, TimeoutError)):
        return True
    return isinstance(e, urllib.error.URLError) and isinstance(getattr(e, "reason", None), (socket.timeout, TimeoutError))


class _Chunks:
    """A file read in 1 MB chunks for http.client, reporting progress."""

    def __init__(self, fh: Any, on_chunk: Optional[Callable[[int], None]]):
        self.fh = fh
        self.on_chunk = on_chunk
        self.sent = 0

    def read(self, _size: int = -1) -> bytes:
        block = self.fh.read(UPLOAD_CHUNK)
        if block:
            self.sent += len(block)
            if self.on_chunk is not None:
                self.on_chunk(self.sent)
        return block


class Supabase:
    def __init__(self, url: str, key: str, *, bucket: str = "editor-stills", timeout: float = 60):
        if not url or not key:
            raise SupabaseError("DESK_SUPABASE_URL and DESK_SUPABASE_KEY are required")
        self.url = url.rstrip("/")
        self.key = key
        self.bucket = bucket
        self.timeout = timeout

    # ---- plumbing --------------------------------------------------------
    def _headers(self, prefer: Optional[str] = None, extra: Optional[dict[str, str]] = None) -> dict[str, str]:
        h = {"apikey": self.key, "Authorization": f"Bearer {self.key}", "Accept": "application/json"}
        if prefer:
            h["Prefer"] = prefer
        if extra:
            h.update(extra)
        return h

    def rest(self, method: str, path: str, *, json_body: Any = None, prefer: Optional[str] = None, retries: int = 2) -> Any:
        headers = self._headers(prefer)
        data = None
        if json_body is not None:
            headers["Content-Type"] = "application/json"
            data = json.dumps(json_body, ensure_ascii=False).encode("utf-8")
        _, _, body = http.request(
            method, f"{self.url}/rest/v1/{path}", headers=headers, data=data,
            timeout=self.timeout, retries=retries, ok_statuses=(200, 201, 204),
        )
        if not body:
            return None
        try:
            return json.loads(body.decode("utf-8"))
        except (ValueError, UnicodeDecodeError):
            return body.decode("utf-8", "replace")

    def select(self, table: str, params: str) -> list[dict[str, Any]]:
        rows = self.rest("GET", f"{table}?{params}")
        return rows if isinstance(rows, list) else []

    def upsert(self, table: str, rows: list[dict[str, Any]], on_conflict: str) -> int:
        if not rows:
            return 0
        groups: dict[tuple[str, ...], list[dict[str, Any]]] = {}
        for row in rows:
            groups.setdefault(tuple(sorted(row.keys())), []).append(row)
        for group in groups.values():
            for i in range(0, len(group), 200):
                self.rest(
                    "POST", f"{table}?on_conflict={on_conflict}",
                    json_body=group[i : i + 200],
                    prefer="resolution=merge-duplicates,return=minimal",
                )
        return len(rows)

    def patch(self, table: str, where: str, body: dict[str, Any]) -> None:
        if not body:
            return
        self.rest("PATCH", f"{table}?{where}", json_body=body, prefer="return=minimal")

    def delete(self, table: str, where: str) -> None:
        self.rest("DELETE", f"{table}?{where}", prefer="return=minimal")

    def ping(self) -> bool:
        self.rest("GET", "editor_jobs?select=task_id&limit=1")
        return True

    # ---- database functions and the private buckets ----------------------
    def rpc(
        self,
        name: str,
        args: dict[str, Any],
        *,
        retry: bool = True,
        sleep: Callable[[float], None] = time.sleep,
    ) -> Any:
        """Call a database function. A refusal with PostgREST's JSON error
        becomes RpcError and is never retried: the decks' functions refuse
        on purpose (a lost claim, a bad argument), and a second try would
        refuse the same way. A network failure or a 5xx without that body is
        tried three times, unless `retry` is false: a call that is not
        idempotent (the import claim) is sent once, because a retry after a
        lost answer would take a second import."""
        for attempt in range(3 if retry else 1):
            try:
                return self.rest("POST", f"rpc/{name}", json_body=args, retries=0)
            except http.HttpError as e:
                err = rpc_error(e)
                if err is not None:
                    raise err from None
                if not retry or attempt == 2 or not (e.status == 0 or e.status in (500, 502, 503, 504)):
                    raise
                sleep(2 ** attempt)
        return None

    def storage_list(self, bucket: str, *, prefix: str = "", limit: int = 1) -> Any:
        """One page of a bucket's listing: the doctor's proof the bucket is there."""
        _, _, body = http.request(
            "POST", f"{self.url}/storage/v1/object/list/{http.quote(bucket)}",
            headers=self._headers(), json_body={"prefix": prefix, "limit": int(limit)},
            timeout=self.timeout, retries=1, ok_statuses=(200,),
        )
        return json.loads(body.decode("utf-8")) if body else None

    def upload_file(
        self,
        bucket: str,
        path: str,
        file_path: str,
        content_type: str,
        *,
        upsert: bool = False,
        on_chunk: Optional[Callable[[int], None]] = None,
        timeout: float = 300,
        sleep: Callable[[float], None] = time.sleep,
    ) -> str:
        """Stream a file from disk into a private bucket.

        Returns "uploaded", or "exists" when Storage says the object is
        already there (the caller then asks the database to check its
        bytes). Raises StorageTooLarge when Storage refuses it for its size,
        and HttpError for anything else. Its own loop, not http.request: the
        file is opened afresh on every attempt, so a retry sends the whole
        body again, and it is retried once on a timeout or a 5xx.
        """
        url = f"{self.url}/storage/v1/object/{http.quote(bucket)}/" + "/".join(http.quote(seg) for seg in path.split("/"))
        size = os.path.getsize(file_path)
        headers = self._headers(extra={
            "Content-Type": content_type,
            "x-upsert": "true" if upsert else "false",
            "cache-control": "3600",
            "Content-Length": str(size),
            "User-Agent": http.USER_AGENT,
        })
        for attempt in range(2):
            last = attempt == 1
            try:
                with open(file_path, "rb") as fh:
                    req = urllib.request.Request(url, data=_Chunks(fh, on_chunk), headers=headers, method="POST")
                    with urllib.request.urlopen(req, timeout=timeout) as res:
                        res.read()
                return "uploaded"
            except urllib.error.HTTPError as e:
                try:
                    body = e.read() or b""
                except Exception:  # noqa: BLE001 - a body we cannot read is an empty one
                    body = b""
                if _storage_duplicate(e.code, body):
                    return "exists"
                if _storage_too_large(e.code, body):
                    raise StorageTooLarge(e.code, body[:300].decode("utf-8", "replace"), body, url) from None
                if 500 <= e.code < 600 and not last:
                    sleep(2)
                    continue
                raise http.HttpError(e.code, body[:300].decode("utf-8", "replace"), body, url) from None
            except (urllib.error.URLError, OSError, http_client.HTTPException) as e:
                if _is_timeout(e) and not last:
                    sleep(2)
                    continue
                raise http.HttpError(0, f"{type(e).__name__}: {e}", b"", url) from None
        raise http.HttpError(0, "upload failed", b"", url)

    @staticmethod
    def _row(d: dict[str, Any], allowed: set[str]) -> dict[str, Any]:
        row = {k: v for k, v in d.items() if k in allowed}
        for k in JSON_COLUMNS:
            if k in row and row[k] is None:
                row[k] = []
        return row

    # ---- jobs ------------------------------------------------------------
    def existing_jobs(self, task_ids: Iterable[str]) -> dict[str, dict[str, Any]]:
        ids = [t for t in dict.fromkeys(task_ids) if t]
        out: dict[str, dict[str, Any]] = {}
        for i in range(0, len(ids), 100):
            chunk = ids[i : i + 100]
            rows = self.select(
                "editor_jobs",
                f"select=task_id,state,ready,prepared_at,attempts,script_task_id,error,footage_url,raw_url&task_id=in.({','.join(_q(t) for t in chunk)})",
            )
            for r in rows:
                out[r["task_id"]] = r
        return out

    def store_jobs(self, rows: list[dict[str, Any]], *, create: bool = True) -> dict[str, int]:
        """Board rows in. A job already known keeps its worker state; a new one starts at `new`.

        With `create` off, only jobs already here are updated: a closed card
        is not work to add, but a job that was open takes its new status.

        The one exception: a known job whose footage link changed goes back
        to `new`, because the link it was judged on is gone. A job blocked on
        a link that was not shared, or not Drive at all, used to stay blocked
        after someone fixed the card: on 2026-10-22, 34 of 63 jobs were
        blocked and none of them would ever be read again on its own.
        """
        stamp = now_iso()
        have = self.existing_jobs([r.get("task_id", "") for r in rows])
        fresh: list[dict[str, Any]] = []
        known: list[dict[str, Any]] = []
        for r in rows:
            tid = r.get("task_id")
            if not tid:
                continue
            if tid in have:
                body = self._row(r, BOARD_COLUMNS)
                body["updated_at"] = stamp
                if _link_changed(have[tid], r):
                    body.update({"state": "new", "attempts": 0})
                known.append({**body, "task_id": tid})
            elif create:
                body = self._row(r, JOB_COLUMNS)
                body.update({"state": "new", "ready": False, "attempts": 0, "updated_at": stamp})
                fresh.append(body)
        self.upsert("editor_jobs", fresh, "task_id")
        self.upsert("editor_jobs", known, "task_id")
        return {"new": len(fresh), "updated": len(known)}

    def job(self, task_id: str) -> Optional[dict[str, Any]]:
        rows = self.select("editor_jobs", f"select=*&task_id=eq.{http.quote(task_id)}&limit=1")
        return rows[0] if rows else None

    def jobs_to_prepare(self, limit: int, *, retry_blocked_hours: float = 0) -> list[dict[str, Any]]:
        """Open jobs the worker has not finished, oldest first, tried fewer than four times.

        A job whose card is finished (cancelled, complete, live) is skipped:
        reading its footage would spend money on work nobody will do. Live is
        not a closed status to the sync, so its status still updates.

        Room left over goes to blocked jobs that have a footage link and were
        last looked at more than `retry_blocked_hours` ago, longest wait first.
        Footage often lands in the folder after the card is made, and nobody
        presses Rescan. Looking again is a folder listing; a file already
        read is skipped, so only new footage costs anything.
        """
        rows = self.select(
            "editor_jobs",
            "select=*&state=in.(\"new\",\"stale\")&attempts=lt.4&order=opened_at.asc&limit=" + str(int(limit)),
        )
        out = [r for r in rows if _letters(r.get("status")) not in FINISHED]
        room = int(limit) - len(out)
        if room <= 0 or retry_blocked_hours <= 0:
            return out
        before = (datetime.now(timezone.utc) - timedelta(hours=retry_blocked_hours)).replace(microsecond=0)
        stamp = before.isoformat().replace("+00:00", "Z")
        blocked = self.select(
            "editor_jobs",
            f"select=*&state=eq.blocked&prepared_at=lt.{stamp}&order=prepared_at.asc&limit=200",
        )
        again = [
            r for r in blocked
            if _letters(r.get("status")) not in FINISHED and (r.get("footage_url") or r.get("raw_url"))
        ]
        return out + again[:room]

    def retire_missing(self, on_board: Iterable[str], stamp: str) -> dict[str, Any]:
        """Mark jobs whose card is no longer on the board.

        A card deleted in ClickUp used to leave a job here forever: "jg
        design" sat in the cockpit as Blocked for a day after the card was
        deleted (found 2026-09-19). Rows are kept rather than deleted, because
        the transcripts and storyboards under them cost real money to make;
        they move to `gone` and drop out of every view.

        This refuses to run on a suspiciously small board. A half-failed
        ClickUp read returning three cards must not retire the other thirty.
        """
        have = {str(t) for t in on_board if t}
        stored = self.select("editor_jobs", "select=task_id,state&state=neq.gone&limit=1000")
        if not stored:
            return {"retired": 0}
        if len(have) < max(1, len(stored) // 2):
            return {"retired": 0, "refused": f"the board returned only {len(have)} cards for {len(stored)} jobs"}
        missing = [r["task_id"] for r in stored if r.get("task_id") not in have]
        for task_id in missing:
            self.patch(
                "editor_jobs",
                f"task_id=eq.{http.quote(task_id)}",
                {"state": "gone", "error": "the card is no longer on the board", "updated_at": stamp},
            )
        return {"retired": len(missing), "task_ids": missing}

    def mark_job(self, task_id: str, **fields: Any) -> None:
        fields["updated_at"] = now_iso()
        self.patch("editor_jobs", f"task_id=eq.{http.quote(task_id)}", fields)

    # ---- assets, versions, notes -----------------------------------------
    def store_assets(self, rows: list[dict[str, Any]]) -> int:
        stamp = now_iso()
        clean = []
        for r in rows:
            body = self._row(r, ASSET_COLUMNS)
            body.setdefault("at", stamp)
            body["updated_at"] = stamp
            clean.append(body)
        return self.upsert("editor_assets", clean, "id")

    def assets(self, task_id: str) -> list[dict[str, Any]]:
        return self.select("editor_assets", f"select=*&task_id=eq.{http.quote(task_id)}&order=at.asc")

    def delete_assets(self, task_id: str, ids: list[str]) -> int:
        """Remove one job's clips by row id. Both filters, so a bad id list can
        never reach another job's clips."""
        if not ids:
            return 0
        listed = ",".join(f'"{i}"' for i in ids)
        self.delete("editor_assets", f"task_id=eq.{http.quote(task_id)}&id=in.({http.quote(listed)})")
        return len(ids)

    def store_version(self, row: dict[str, Any]) -> str:
        stamp = now_iso()
        body = self._row(row, VERSION_COLUMNS)
        body.setdefault("at", stamp)
        body["updated_at"] = stamp
        self.upsert("editor_versions", [body], "id")
        return str(body.get("id") or "")

    def versions(self, task_id: str) -> list[dict[str, Any]]:
        return self.select("editor_versions", f"select=*&task_id=eq.{http.quote(task_id)}&order=n.asc")

    def store_notes(self, rows: list[dict[str, Any]]) -> int:
        return self.upsert("editor_notes", [self._row(r, NOTE_COLUMNS) for r in rows], "id")

    def notes(self, task_id: str) -> list[dict[str, Any]]:
        return self.select("editor_notes", f"select=*&task_id=eq.{http.quote(task_id)}&order=at.asc")

    # ---- people ----------------------------------------------------------
    def seats_from_board(self, people: list[dict[str, str]], stamp: str) -> dict[str, int]:
        """Whoever is Assigned Editor on an open video card gets a seat.

        The desk writes `via_clickup` and nothing else. The portal writes
        `via_portal`; `active` is computed by the database from the two, so
        the two syncs cannot undo each other however they interleave.

        A seat is taken away the same way it was given: anyone this worker
        granted who is no longer on the board has their own flag cleared, and
        if the portal also granted them they keep their seat regardless.
        """
        want = {}
        for p in people:
            email = str(p.get("email") or "").strip().lower()
            if email:
                want[email] = str(p.get("name") or "")
        rows = [
            {"email": e, "via_clickup": True, "clickup_seen_at": stamp, **({"name": n} if n else {})}
            for e, n in want.items()
        ]
        added = self.upsert("editor_people", rows, "email") if rows else 0

        held = self.select("editor_people", "select=email&via_clickup=is.true")
        stale = [r["email"] for r in held if str(r.get("email") or "").lower() not in want]
        for email in stale:
            self.patch("editor_people", f"email=eq.{http.quote(email)}", {"via_clickup": False})
        return {"granted": added, "revoked": len(stale)}

    # ---- team meetings, as Fathom recorded them --------------------------
    # Their own table since 2026-09-27: `team_meetings` is the cockpit's
    # meetings (convex/team.ts), and writing recordings there failed every
    # hour with PGRST204.
    def store_meetings(self, rows: list[dict[str, Any]]) -> int:
        stamp = now_iso()
        clean = []
        for r in rows:
            body = {k: v for k, v in r.items() if k in MEETING_COLUMNS}
            if not body.get("recording_id"):
                continue
            body["synced_at"] = stamp
            clean.append(body)
        return self.upsert("team_recordings", clean, "recording_id")

    # ---- the swipe file --------------------------------------------------
    def known_ideation_keys(self, keys: Iterable[str]) -> list[str]:
        """Which of these the ideation board has already seen, in any state.
        A dismissed idea must not come back on the next sync."""
        wanted = [k for k in dict.fromkeys(keys) if k]
        out: list[str] = []
        for i in range(0, len(wanted), 100):
            chunk = wanted[i : i + 100]
            rows = self.select(
                "ideation_posts",
                f"select=key&key=in.({','.join(_q(k) for k in chunk)})",
            )
            out += [str(r.get("key")) for r in rows if r.get("key")]
        return out

    def known_foreplay_ids(self, limit: int = 5000) -> list[str]:
        """What we already hold, so a sync can stop rather than pay again."""
        rows = self.select("foreplay_ads", f"select=id&limit={int(limit)}")
        return [str(r.get("id")) for r in rows if r.get("id")]

    # ---- Frame.io --------------------------------------------------------
    def frameio_auth(self) -> dict[str, Any]:
        rows = self.select("frameio_auth", "select=*&id=eq.default&limit=1")
        return rows[0] if rows else {}

    def frameio_refreshed(self, refresh_token: str) -> None:
        """Write the new refresh token down. Adobe spends the old one on
        every refresh, so failing to store this locks the worker out."""
        self.upsert(
            "frameio_auth",
            [{
                "id": "default",
                "refresh_token": refresh_token,
                "refreshed_at": now_iso(),
                "error": None,
                "updated_at": now_iso(),
            }],
            "id",
        )

    def frameio_failed(self, why: str) -> None:
        self.upsert(
            "frameio_auth",
            [{"id": "default", "error": why[:300], "updated_at": now_iso()}],
            "id",
        )

    def job_by_frameio_file(self, file_id: str) -> dict[str, Any]:
        """The job whose cut is that Frame.io file, if any. A comment on
        something that is not one of our cuts is ignored, not an error."""
        if not file_id:
            return {}
        rows = self.select(
            "editor_jobs",
            "select=task_id,frameio_file_id,frameio_version"
            f"&frameio_file_id=eq.{http.quote(file_id)}&limit=1",
        )
        return rows[0] if rows else {}

    def frameio_jobs(self, *, limit: int = 40) -> list[dict[str, Any]]:
        """Open jobs with a cut in Frame.io, newest first."""
        return self.select(
            "editor_jobs",
            "select=task_id,frameio_file_id,frameio_version,status"
            "&frameio_file_id=not.is.null"
            f"&order=updated_at.desc&limit={int(limit)}",
        )

    def board_state(self) -> dict[str, dict[str, Any]]:
        """What we already know about each board, so a sync can skip the
        ones it read recently rather than paying for them again."""
        rows = self.select("foreplay_boards", "select=id,name,ads,ads_synced_at&limit=500")
        return {str(r["id"]): r for r in rows if r.get("id")}

    def store_boards(self, boards: list[dict[str, Any]]) -> list[str]:
        """Record every board and return the names of the ones we had never
        seen, so a board somebody adds is noticed rather than ignored."""
        if not boards:
            return []
        stamp = now_iso()
        known = {
            str(r.get("id"))
            for r in self.select("foreplay_boards", "select=id&limit=500")
        }
        fresh = [b for b in boards if str(b.get("id")) not in known]
        rows = []
        for b in boards:
            if not b.get("id"):
                continue
            row = {
                "id": str(b["id"]), "name": b.get("name"),
                "feeds_ideation": bool(b.get("feeds_ideation")),
                "ads": int(b.get("ads") or 0),
                "last_seen_at": stamp,
            }
            # Only a board we actually read gets a fresh read time, or a
            # skipped board would look current and never be read again.
            if b.get("read"):
                row["ads_synced_at"] = stamp
            rows.append(row)
        self.upsert("foreplay_boards", rows, "id")
        return [str(b.get("name") or b.get("id")) for b in fresh]

    def store_foreplay(self, rows: list[dict[str, Any]]) -> int:
        stamp = now_iso()
        clean = []
        for r in rows:
            body = {k: v for k, v in r.items() if k in FOREPLAY_COLUMNS}
            if not body.get("id"):
                continue
            body["synced_at"] = stamp
            clean.append(body)
        return self.upsert("foreplay_ads", clean, "id")

    # ---- clients ---------------------------------------------------------
    def store_clients(self, rows: list[dict[str, Any]]) -> int:
        """The roster from Clients - Mahara. A company already known keeps the
        document text it has unless this row carries fresher text."""
        stamp = now_iso()
        clean = []
        for r in rows:
            body = self._row(r, CLIENT_COLUMNS)
            if not body.get("task_id"):
                continue
            body.setdefault("synced_at", stamp)
            body["updated_at"] = stamp
            clean.append(body)
        return self.upsert("editor_clients", clean, "task_id")

    def clients(self, task_ids: Optional[Iterable[str]] = None) -> list[dict[str, Any]]:
        if task_ids is None:
            return self.select("editor_clients", "select=*&order=name.asc&limit=400")
        ids = [t for t in dict.fromkeys(task_ids) if t]
        if not ids:
            return []
        out: list[dict[str, Any]] = []
        for i in range(0, len(ids), 100):
            chunk = ids[i : i + 100]
            out += self.select("editor_clients", f"select=*&task_id=in.({','.join(_q(t) for t in chunk)})")
        return out

    def client(self, task_id: str) -> Optional[dict[str, Any]]:
        rows = self.select("editor_clients", f"select=*&task_id=eq.{http.quote(task_id)}&limit=1")
        return rows[0] if rows else None

    # ---- the Brand Blueprint (the cockpit's table, read only) -------------
    def blueprint_parts(self, since: datetime) -> list[dict[str, Any]]:
        """Each Blueprint's card and parts, for records changed since `since`.

        A part's first send also moves the row's updated_at, so a record not
        touched since then cannot hold a part sent since then: the filter only
        narrows the read. Only task_id and parts are asked for, never the
        answers or who gave them.
        """
        stamp = since.astimezone(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
        return self.select(
            "cockpit_blueprints",
            f"select=task_id,parts&updated_at=gte.{http.quote(stamp)}&order=updated_at.desc&limit=500",
        )

    # ---- our own copy of an ad -------------------------------------------
    def store_winner_file(self, row: dict[str, Any]) -> None:
        body = {k: v for k, v in row.items() if k in
                {"ad_id", "video_id", "file_path", "file_bytes", "file_error"}}
        if not body.get("ad_id"):
            return
        body["file_at"] = now_iso()
        self.upsert("winner_ads", [body], "ad_id")

    def upload_ad_video(self, ad_id: str, blob: bytes) -> str:
        path = f"{ad_id}.mp4"
        headers = self._headers(extra={"Content-Type": "video/mp4", "x-upsert": "true"})
        http.request(
            "POST", f"{self.url}/storage/v1/object/ad-videos/{http.quote(path)}",
            headers=headers, data=blob, timeout=300, retries=1, ok_statuses=(200, 201),
        )
        return path

    # ---- stills ----------------------------------------------------------
    def upload_still(self, task_id: str, name: str, blob: bytes, content_type: str = "image/jpeg") -> str:
        path = f"{task_id}/{name}"
        headers = self._headers(extra={"Content-Type": content_type, "x-upsert": "true"})
        http.request(
            "POST", f"{self.url}/storage/v1/object/{self.bucket}/{http.quote(path)}",
            headers=headers, data=blob, timeout=self.timeout, retries=1, ok_statuses=(200, 201),
        )
        return path

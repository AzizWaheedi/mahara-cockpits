-- 9. RPC: Get Dashboard Summary
CREATE OR REPLACE FUNCTION public.cockpit_get_dashboard_summary(
  p_role text,
  p_day date
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
  v_role text;
  v_summary jsonb;
BEGIN
  v_uid := auth.uid();
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Sign in before fetching dashboard summary' USING ERRCODE = '42501';
  END IF;

  v_role := trim(coalesce(p_role, ''));
  IF v_role NOT IN ('media_buyer', 'csm', 'creative', 'editor') OR p_day IS NULL THEN
    RAISE EXCEPTION 'Invalid role or day' USING ERRCODE = '22023';
  END IF;

  IF NOT (public.cockpit_has_role(v_role) OR public.cockpit_has_role('admin') OR public.cockpit_is_ceo()) THEN
    RAISE EXCEPTION 'Permission denied for dashboard summary: %', v_role USING ERRCODE = '42501';
  END IF;

  SELECT jsonb_build_object(
    'role', v_role,
    'day', p_day,
    'campaigns_count', (SELECT count(*) FROM public.cockpit_campaigns),
    'ads_count', (SELECT count(*) FROM public.cockpit_ads),
    'checks_total', (
      SELECT count(*) FROM public.cockpit_daily_checks
      WHERE role = v_role AND day = p_day AND source_deleted = false
    ),
    'checks_done', (
      SELECT count(*) FROM public.cockpit_daily_checks
      WHERE role = v_role AND day = p_day AND done = true AND source_deleted = false
    ),
    'decisions_today', (
      SELECT count(*) FROM public.cockpit_decisions
      WHERE role = v_role AND day = p_day
    ),
    'eod_submitted', (
      SELECT coalesce(submitted_at IS NOT NULL, false)
      FROM public.cockpit_eod_reports
      WHERE role = v_role AND day = p_day
    ),
    'spend_7d', (SELECT coalesce(sum(spend_7d), 0) FROM public.cockpit_campaigns),
    'leads_7d', (SELECT coalesce(sum(leads_7d), 0) FROM public.cockpit_campaigns)
  ) INTO v_summary;

  RETURN v_summary;
END;
$$;


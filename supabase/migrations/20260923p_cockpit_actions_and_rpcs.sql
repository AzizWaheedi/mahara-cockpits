    RAISE EXCEPTION 'Permission denied to remove decision' USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.cockpit_decisions WHERE id = p_id;
  RETURN true;
END;
$$;

-- 6. RPC: Update Client Profile
CREATE OR REPLACE FUNCTION public.cockpit_update_client_profile(
  p_client_name text,
  p_health text DEFAULT NULL,
  p_stage text DEFAULT NULL,
  p_service text DEFAULT NULL,
  p_notes jsonb DEFAULT NULL,
  p_kpi jsonb DEFAULT NULL,
  p_overview jsonb DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
  v_name text;
  v_id bigint;
BEGIN
  v_uid := auth.uid();
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Sign in before updating a client profile' USING ERRCODE = '42501';
  END IF;

  IF NOT (
    public.cockpit_has_role('csm')
    OR public.cockpit_has_role('media_buyer')
    OR public.cockpit_has_role('admin')
    OR public.cockpit_is_ceo()
  ) THEN
    RAISE EXCEPTION 'Permission denied to update client profiles' USING ERRCODE = '42501';
  END IF;

  v_name := trim(coalesce(p_client_name, ''));
  IF v_name = '' THEN
    RAISE EXCEPTION 'client_name cannot be empty' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.cockpit_client_profiles (
    client_name,
    health,
    stage,
    service,
    notes,
    kpi,
    overview,
    source_system,
    updated_at
  ) VALUES (
    v_name,
    p_health,
    p_stage,
    p_service,
    coalesce(p_notes, '[]'::jsonb),
    coalesce(p_kpi, '{}'::jsonb),
    coalesce(p_overview, '{}'::jsonb),
    'supabase',
    now()
  )
  ON CONFLICT (client_name) DO UPDATE
  SET health = coalesce(EXCLUDED.health, public.cockpit_client_profiles.health),
      stage = coalesce(EXCLUDED.stage, public.cockpit_client_profiles.stage),
      service = coalesce(EXCLUDED.service, public.cockpit_client_profiles.service),
      notes = coalesce(EXCLUDED.notes, public.cockpit_client_profiles.notes),
      kpi = coalesce(EXCLUDED.kpi, public.cockpit_client_profiles.kpi),
      overview = coalesce(EXCLUDED.overview, public.cockpit_client_profiles.overview),
      source_system = 'supabase',
      updated_at = now()
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;


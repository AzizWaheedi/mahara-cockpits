CREATE OR REPLACE FUNCTION public.cockpit_client_allowed(p_name text)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF p_name IS NULL OR btrim(p_name)='' THEN RETURN false; END IF;
  IF public.cockpit_has_role('admin') OR public.cockpit_is_ceo() THEN RETURN true; END IF;
  RETURN EXISTS (
    SELECT 1 FROM public.cockpit_members m JOIN auth.users u ON u.id=m.auth_user_id
    WHERE m.auth_user_id=auth.uid() AND m.active AND u.email_confirmed_at IS NOT NULL
      AND m.email=lower(btrim(u.email))
      AND (cardinality(m.clients)=0 OR EXISTS (
        SELECT 1 FROM unnest(m.clients) n WHERE lower(btrim(n))=lower(btrim(p_name))
      ))
  );
END $$;

CREATE OR REPLACE FUNCTION public.cockpit_csm_actor()
RETURNS uuid LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF (public.cockpit_has_role('csm') OR public.cockpit_is_ceo()) IS NOT TRUE THEN
    RAISE EXCEPTION 'Active client-success access required' USING ERRCODE='42501';
  END IF;
  RETURN auth.uid();
END $$;

CREATE OR REPLACE FUNCTION public.cockpit_csm_hot_visible(p_name text,p_owner uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
  SELECT (p_name='' AND (p_owner=auth.uid() OR public.cockpit_is_ceo()))
    OR (p_name<>'' AND public.cockpit_client_allowed(p_name));
$$;
CREATE OR REPLACE FUNCTION public.cockpit_csm_month_valid(p_month text)
RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path='' AS $$
  SELECT coalesce(p_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$' AND left(p_month,4)<>'0000',false);
$$;
CREATE OR REPLACE FUNCTION public.cockpit_is_money_loose(p_text text)
RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path='' AS $$
  SELECT coalesce(p_text,'') ~* 'invoice|payment|past due|billing|pause|refund|card';
$$;

CREATE TABLE IF NOT EXISTS public.cockpit_csm_client_preferences (
  client_profile_id bigint PRIMARY KEY REFERENCES public.cockpit_client_profiles(id),
  language text NOT NULL CHECK(length(btrim(language)) BETWEEN 1 AND 30),
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  source_system text NOT NULL DEFAULT 'supabase', source_deployment text, source_id text

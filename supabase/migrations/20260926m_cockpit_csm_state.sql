  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_profile_id bigint NOT NULL REFERENCES public.cockpit_client_profiles(id),
  loose_text text NOT NULL,
  text_hash text GENERATED ALWAYS AS (md5(loose_text)) STORED,
  cleared_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  cleared_at timestamptz NOT NULL DEFAULT now(),
  source_system text NOT NULL DEFAULT 'supabase', source_deployment text, source_id text,
  UNIQUE(client_profile_id,text_hash)
);
CREATE TABLE IF NOT EXISTS public.cockpit_csm_money_goals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  owner_email text NOT NULL,
  month text NOT NULL CHECK(public.cockpit_csm_month_valid(month)),
  target numeric CHECK(target IS NULL OR target>=0),
  clients integer CHECK(clients IS NULL OR clients>=0),
  counts jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(counts)='object'),
  updated_at timestamptz NOT NULL DEFAULT now(),
  source_system text NOT NULL DEFAULT 'supabase', source_deployment text, source_id text,
  UNIQUE(owner_id,month)
);


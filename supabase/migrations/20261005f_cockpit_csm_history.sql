-- This resolves recorded historical identity, not permission to act today.
CREATE FUNCTION public.cockpit_csm_history_owner(p_email text) RETURNS uuid
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
DECLARE matched bigint; resolved uuid;
BEGIN
 IF nullif(btrim(p_email),'') IS NULL THEN RETURN NULL;END IF;
 SELECT count(*),max(u.id::text)::uuid INTO matched,resolved
 FROM auth.users u JOIN public.cockpit_members m ON m.auth_user_id=u.id
 WHERE u.email_confirmed_at IS NOT NULL AND m.email=lower(btrim(u.email))
  AND lower(btrim(u.email))=lower(btrim(p_email));
 IF matched<>1 THEN RETURN NULL;END IF;
 RETURN resolved;
END $$;
REVOKE ALL ON FUNCTION public.cockpit_csm_history_owner(text) FROM PUBLIC,anon,authenticated,service_role;


CREATE OR REPLACE FUNCTION public.cockpit_csm_call_briefs(p_client_name text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF NOT(public.cockpit_has_role('csm') OR public.cockpit_has_role('media_buyer') OR public.cockpit_is_ceo()) THEN
    RAISE EXCEPTION 'Current confirmed cockpit access required' USING ERRCODE='42501';
  END IF;
  IF p_client_name IS NOT NULL AND public.cockpit_client_allowed(p_client_name) IS NOT TRUE THEN
    RAISE EXCEPTION 'Client access denied' USING ERRCODE='42501';
  END IF;
  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object(
      '_id', coalesce(source_id, id::text),
      'clientName', client_name,
      'key', key,
      'jobId', job_id,
      'status', status,
      'overall', overall,
      'perCall', per_call,
      'at', extract(epoch FROM at) * 1000
    ) ORDER BY at DESC, id DESC)
    FROM public.cockpit_media_call_briefs
    WHERE (public.cockpit_has_role('csm') OR public.cockpit_has_role('media_buyer') OR public.cockpit_is_ceo())
      AND public.cockpit_client_allowed(client_name)
      AND (p_client_name IS NULL OR lower(btrim(client_name)) = lower(btrim(p_client_name)))
  ), '[]'::jsonb);
END $$;
REVOKE ALL ON FUNCTION public.cockpit_csm_call_briefs(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cockpit_csm_call_briefs(text) TO authenticated;

COMMIT;

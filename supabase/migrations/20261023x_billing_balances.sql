-- money.js nameKey: NFKD, combining marks stripped, lower case, letters and
-- digits only. The marks are listed rather than left to [[:alnum:]], which
-- counts some Arabic marks as letters under one locale and not under another.
CREATE OR REPLACE FUNCTION public.cockpit_name_key(p_text text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path='' AS $$
  SELECT regexp_replace(
           regexp_replace(normalize(lower(coalesce(p_text, '')), NFKD),
             '[̀-ͯ҃-҉֑-ׇؐ-ًؚ-ٰٟۖ-ۜ۟-۪ۤۧۨ-ۭ࣓-ࣿ᪰-᫿᷀-᷿⃐-⃿︠-︯]',
             '', 'g'),
           '[^[:alnum:]]', '', 'g')
$$;

-- Is a card on the pending payments list (PLAN 1.2 "Scope")? On the books
-- (active, or in onboarding), not paused, churned, internal or a test, and
-- not GHOSTED straight from Paused. GHOSTED cards stay in (the rule folds
-- them into Gone quiet). p_ceo also lets in SALES TEAM TO CONTACT cards, the
-- CEO's Back with sales group. One test for the read and for the writes, so
-- nothing is written where no screen shows it.
CREATE OR REPLACE FUNCTION public.cockpit_billing_card_listed(p_task text, p_ceo boolean)
RETURNS boolean LANGUAGE sql STABLE SET search_path='' AS $$
  SELECT coalesce((
    SELECT (coalesce(a.stage_group, '') IN ('active', 'pipeline') OR (coalesce(p_ceo, false) AND a.stage_group = 'sales'))
       AND a.paused_on IS NULL AND a.churn_date IS NULL
       AND a.client_name !~* 'playing account|\[internal test\]'
       AND NOT (upper(btrim(coalesce(a.client_status, ''))) = 'GHOSTED' AND coalesce((
             SELECT h.stage FROM public.cockpit_client_billing_days h
             WHERE h.clickup_task_id = a.clickup_task_id AND h.stage IS DISTINCT FROM a.client_status
             ORDER BY h.day DESC LIMIT 1), '') ~* '^\s*paused')
    FROM public.cockpit_billing_accounts a WHERE a.clickup_task_id = p_task), false)
$$;

-- The name to show for whoever wrote a row: cockpit_people by email, then the
-- portal seat's name, then a name typed instead of an email (Maher, Faris).
-- Never the email itself; null when no name is on record.
CREATE OR REPLACE FUNCTION public.cockpit_billing_person_name(p_who text)
RETURNS text LANGUAGE sql STABLE SET search_path='' AS $$
  SELECT CASE WHEN nullif(btrim(coalesce(p_who, '')), '') IS NULL THEN NULL ELSE coalesce(
    (SELECT nullif(btrim(p.name), '') FROM public.cockpit_people p
      WHERE lower(btrim(p.email)) = lower(btrim(p_who)) ORDER BY p.active DESC, p.id LIMIT 1),
    (SELECT nullif(btrim(m.name), '') FROM public.cockpit_members m
      WHERE m.email = lower(btrim(p_who)) AND nullif(btrim(m.name), '') IS NOT NULL ORDER BY m.active DESC LIMIT 1),
    CASE WHEN p_who !~ '@' THEN initcap(btrim(p_who)) END) END
$$;

-- Every signed, live deal and the card it belongs to (PLAN 1.2 "deal for a card"):
--   a live CEO link first; then the card its ledger payments were credited to;
--   then the card whose name or alias key equals the deal's business key
--   (4+ characters); then one containing the other (both 6+ characters, the
--   longer card key wins). A card that is on the books (active, onboarding or
--   back with sales) beats a gone one. A deal two such cards claim is a
--   conflict, unless the CEO linked it. Voided deals, deals with no signing
--   time and "test" deals are left out. clickup_task_id is null for a deal no
--   card claims.
CREATE OR REPLACE FUNCTION public.cockpit_billing_deal_assignments()
RETURNS TABLE(deal_response_id text, signed_at timestamptz, clickup_task_id text, matched_by text,
              conflict boolean, conflict_with text[], linked_by text, link_id bigint)
LANGUAGE sql STABLE SET search_path='' AS $$
  WITH deals AS (
    SELECT d.response_id, d.submitted_at, public.cockpit_name_key(d.business_name) AS k
    FROM public.cockpit_sales_deals d
    WHERE NOT d.voided AND d.submitted_at IS NOT NULL
      AND public.cockpit_name_key(d.business_name) <> 'test'
      AND lower(btrim(coalesce(d.business_name, ''))) !~ '^test([^a-z]|$)'
  ),
  cards AS (
    SELECT a.clickup_task_id AS task,
           (coalesce(a.stage_group, '') IN ('active', 'pipeline', 'sales') AND a.paused_on IS NULL AND a.churn_date IS NULL
            AND a.client_name !~* 'playing account|\[internal test\]') AS listable
    FROM public.cockpit_billing_accounts a
  ),
  names AS (
    SELECT a.clickup_task_id AS task, 0 AS alias, public.cockpit_name_key(a.client_name) AS k
    FROM public.cockpit_billing_accounts a
    UNION
    SELECT f.task_id, 1, public.cockpit_name_key(f.name)
    FROM public.cockpit_finance_client_aliases f WHERE f.task_id IS NOT NULL
    UNION
    SELECT f.task_id, 1, public.cockpit_name_key(e.v)
    FROM public.cockpit_finance_client_aliases f
    CROSS JOIN LATERAL jsonb_array_elements_text(CASE WHEN jsonb_typeof(f.aliases) = 'array' THEN f.aliases ELSE '[]'::jsonb END) AS e(v)
    WHERE f.task_id IS NOT NULL
  ),
  cand AS (
    -- rank 0 ledger, 1 exact name, 2 exact alias, 3 one contains the other
    SELECT d.response_id, n.task, CASE WHEN n.k = d.k THEN 1 + n.alias ELSE 3 END AS rank, n.alias, length(n.k) AS klen
    FROM deals d
    JOIN names n ON (length(n.k) >= 4 AND n.k = d.k)
                 OR (length(n.k) >= 6 AND length(d.k) >= 6 AND (strpos(d.k, n.k) > 0 OR strpos(n.k, d.k) > 0))
    UNION
    SELECT dp.deal_response_id, cp.clickup_task_id, 0, 0, 0
    FROM public.cockpit_deal_payments dp
    JOIN public.cockpit_client_payments cp ON cp.payment_id = dp.payment_id AND cp.active
    JOIN deals d ON d.response_id = dp.deal_response_id
    WHERE dp.active
  ),
  carded AS (
    SELECT c.*, k.listable FROM cand c JOIN cards k ON k.task = c.task
  ),
  best AS (
    SELECT DISTINCT ON (c.response_id) c.response_id, c.task, c.rank, c.alias
    FROM carded c
    ORDER BY c.response_id, c.rank, c.listable DESC, c.klen DESC, c.task
  ),
  spread AS (
    SELECT c.response_id, array_agg(DISTINCT c.task ORDER BY c.task) FILTER (WHERE c.listable) AS tasks
    FROM carded c GROUP BY c.response_id
  ),
  links AS (
    SELECT l.id, l.deal_response_id, l.clickup_task_id, l.set_by
    FROM public.cockpit_billing_deal_links l
    WHERE l.cleared_at IS NULL
      AND EXISTS (SELECT 1 FROM public.cockpit_billing_accounts a WHERE a.clickup_task_id = l.clickup_task_id)
  )
  SELECT d.response_id,
         d.submitted_at,
         coalesce(l.clickup_task_id, b.task),
         CASE WHEN l.id IS NOT NULL THEN 'link'
              WHEN b.rank = 0 THEN 'ledger'
              WHEN b.rank IS NULL THEN NULL
              WHEN b.alias = 1 THEN 'alias'
              ELSE 'name' END,
         l.id IS NULL AND coalesce(cardinality(s.tasks), 0) > 1,
         CASE WHEN l.id IS NULL AND coalesce(cardinality(s.tasks), 0) > 1
              THEN array_remove(s.tasks, b.task) ELSE '{}'::text[] END,
         l.set_by,
         l.id
  FROM deals d
  LEFT JOIN best b ON b.response_id = d.response_id
  LEFT JOIN spread s ON s.response_id = d.response_id
  LEFT JOIN links l ON l.deal_response_id = d.response_id
$$;

-- One row per card that has a signed deal: its newest deal of any age, how it
-- was matched, and its older forms (newest first).
CREATE OR REPLACE FUNCTION public.cockpit_billing_deal_cards()
RETURNS TABLE(clickup_task_id text, deal_response_id text, matched_by text, conflict boolean,
              conflict_with text[], linked_by text, other_forms jsonb)
LANGUAGE sql STABLE SET search_path='' AS $$
  WITH a AS (
    SELECT x.*, row_number() OVER (PARTITION BY x.clickup_task_id ORDER BY x.signed_at DESC, x.deal_response_id DESC) AS n
    FROM public.cockpit_billing_deal_assignments() x
    WHERE x.clickup_task_id IS NOT NULL
  )
  SELECT r.clickup_task_id, r.deal_response_id, r.matched_by, r.conflict, r.conflict_with, r.linked_by,
         coalesce((SELECT jsonb_agg(jsonb_build_object('responseId', o.deal_response_id, 'signedAt', o.signed_at)
                                    ORDER BY o.signed_at DESC, o.deal_response_id DESC)
                   FROM a o WHERE o.clickup_task_id = r.clickup_task_id AND o.n > 1), '[]'::jsonb)
  FROM a r WHERE r.n = 1
$$;

-- The payments that count for a deal (PLAN 1.2 "Rails"): the deal ledger's
-- active rows, any day; and the card's own active payments, any side, from
-- seven days before signing, that no other deal's ledger holds. Each payment
-- once; from_ledger says which kind it is.
CREATE OR REPLACE FUNCTION public.cockpit_billing_deal_rails(p_deal text, p_task text)
RETURNS TABLE(payment_id text, day date, usd numeric, rail text, from_ledger boolean, kind text, recorded_at timestamptz)
LANGUAGE sql STABLE SET search_path='' AS $$
  WITH d AS (
    SELECT (s.submitted_at AT TIME ZONE 'Asia/Kuwait')::date AS signed
    FROM public.cockpit_sales_deals s WHERE s.response_id = p_deal AND s.submitted_at IS NOT NULL
  ),
  ledger AS (
    SELECT dp.payment_id, dp.day, dp.usd, dp.rail, true AS from_ledger, dp.kind, dp.recorded_at
    FROM public.cockpit_deal_payments dp
    WHERE dp.deal_response_id = p_deal AND dp.active
  ),
  card AS (
    SELECT cp.payment_id, cp.day, cp.usd, cp.rail, false AS from_ledger, cp.kind, cp.recorded_at
    FROM public.cockpit_client_payments cp CROSS JOIN d
    WHERE p_task IS NOT NULL AND cp.clickup_task_id = p_task AND cp.active AND cp.day >= d.signed - 7
      AND NOT EXISTS (SELECT 1 FROM public.cockpit_deal_payments o
                      WHERE o.payment_id = cp.payment_id AND o.active AND o.deal_response_id <> p_deal)
      AND NOT EXISTS (SELECT 1 FROM ledger l WHERE l.payment_id = cp.payment_id)
  )
  SELECT * FROM ledger
  UNION ALL
  SELECT * FROM card
$$;


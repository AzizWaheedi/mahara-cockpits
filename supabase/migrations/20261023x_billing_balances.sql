-- The billing log is read in the browser by every active seat that is not
-- team-only (cockpit_billing_events_seat, 20261017b). The four kinds this
-- build writes carry a confirmation's dollars, rail and deal, and the reasons
-- for a withdraw or an unlink: only the seats that may read pending payments
-- see them. Restrictive, so it narrows that policy and opens nothing. Each
-- (SELECT ...) is an uncorrelated subquery, evaluated once per query rather
-- than once per row, so the older kinds cost a text comparison per row.
DROP POLICY IF EXISTS cockpit_billing_events_balance_kinds ON public.cockpit_billing_events;
CREATE POLICY cockpit_billing_events_balance_kinds ON public.cockpit_billing_events
  AS RESTRICTIVE FOR SELECT TO authenticated
  USING (kind NOT IN ('confirm', 'unconfirm', 'link', 'unlink')
         OR (SELECT public.cockpit_is_ceo())
         OR (SELECT public.cockpit_has_role('csm'))
         OR (SELECT public.cockpit_has_role('finance')));

-- ---------------------------------------------------------------------------
-- 5. The billing log's kinds: the live list, plus the four new ones
--
-- Built from the constraint as it stands when this runs, never from a list
-- typed here alone: a kind another build added after 23 Oct is kept, not
-- dropped. The 13 kinds read live on 23 Oct are added too (all already
-- there), and a constraint that is missing, or that is not a plain list of
-- kinds, stops the migration with a sentence instead of guessing.

DO $kinds$
DECLARE
  v_def text;
  v_live text[];
  v_kinds text[];
BEGIN
  SELECT pg_get_constraintdef(c.oid) INTO v_def
  FROM pg_constraint c
  WHERE c.conrelid = 'public.cockpit_billing_events'::regclass AND c.conname = 'cockpit_billing_events_kind_check';
  IF v_def IS NULL THEN
    RAISE EXCEPTION 'cockpit_billing_events has no cockpit_billing_events_kind_check; read the live table before applying 20261023x.';
  END IF;
  IF v_def !~* '^CHECK \(+kind ' THEN
    RAISE EXCEPTION 'cockpit_billing_events_kind_check is not a list of kinds (%); read it before applying 20261023x.', v_def;
  END IF;
  SELECT coalesce(array_agg(DISTINCT m[1]), '{}'::text[]) INTO v_live
  FROM regexp_matches(v_def, '''([a-z_]+)''', 'g') AS m;
  IF cardinality(v_live) = 0 THEN
    RAISE EXCEPTION 'No kind could be read from cockpit_billing_events_kind_check (%); read it before applying 20261023x.', v_def;
  END IF;
  SELECT array_agg(DISTINCT k ORDER BY k) INTO v_kinds
  FROM unnest(v_live || ARRAY[
    'method', 'plan', 'amount', 'date', 'extension', 'pause', 'resume', 'payment', 'assign', 'note', 'churn', 'invoice',
    'chase', 'confirm', 'unconfirm', 'link', 'unlink']) AS k;
  ALTER TABLE public.cockpit_billing_events DROP CONSTRAINT cockpit_billing_events_kind_check;
  -- A plain IN list, so a second run reads it back the same way.
  EXECUTE format(
    'ALTER TABLE public.cockpit_billing_events ADD CONSTRAINT cockpit_billing_events_kind_check CHECK (kind IN (%s))',
    (SELECT string_agg(quote_literal(k), ', ' ORDER BY k) FROM unnest(v_kinds) AS k));
END
$kinds$;


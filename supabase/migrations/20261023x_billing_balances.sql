-- 3. Guards: never deleted or truncated; an update only withdraws or clears, once

CREATE OR REPLACE FUNCTION public.cockpit_billing_balance_row_lock()
RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
-- TG_ARGV: the three columns that may be set once, the *_at column second.
DECLARE
  v_old jsonb := pg_catalog.to_jsonb(OLD);
  v_new jsonb := pg_catalog.to_jsonb(NEW);
BEGIN
  IF v_old ->> TG_ARGV[1] IS NOT NULL THEN
    RAISE EXCEPTION '% rows are kept as they were once withdrawn or cleared', TG_TABLE_NAME USING ERRCODE = '42501';
  END IF;
  IF (v_new - TG_ARGV::text[]) IS DISTINCT FROM (v_old - TG_ARGV::text[])
     OR v_new ->> TG_ARGV[0] IS NULL OR v_new ->> TG_ARGV[1] IS NULL OR v_new ->> TG_ARGV[2] IS NULL THEN
    RAISE EXCEPTION '% rows are never edited: withdraw or clear them instead', TG_TABLE_NAME USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END $$;


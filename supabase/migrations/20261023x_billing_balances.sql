-- sections 1.2 and 3.1.
--
-- Aziz, 23 Oct 2026: the Billing section of the CEO and client success
-- cockpits lists the signed clients who have not finished paying: the rest of
-- the money due on the onboarding call, and anyone past onboarding with parts
-- of the plan still unpaid. Cancelled, paused and gone clients stay off it.
--
-- What it adds:
--   cockpit_sales_deals.cash_at_onboarding, .second_payment
--                          two closer-form answers the sales mirror drops
--                          today (filled by sales-mirror once it maps them).
--   cockpit_billing_confirmations
--                          a person's word that a part was paid on Whop, Tap
--                          or an Ecom link. Never money: it is not cash, LTV
--                          or pay. Withdrawn once (withdrawn_* set together),
--                          never edited or deleted.
--   cockpit_billing_deal_links
--                          the CEO's link from a signed deal with no client
--                          card to a card. Feeds this screen only; it does not
--                          change who the money refresh credits. Cleared once,
--                          never edited or deleted.
--   cockpit_billing_events_kind_check gains confirm, unconfirm, link, unlink
--                          (the ClickUp write-back trigger lists its own kinds,
--                          so it queues nothing for them). Rebuilt from the
--                          live list, so no kind added since 23 Oct is lost.
--   cockpit_billing_events_balance_kinds
--                          a restrictive browser policy: those four kinds are
--                          read only by the CEO, client success and finance
--                          (every other seat still reads the older kinds).
--   Helpers (owner only, called by the read and by
--   cockpit_billing_balance_write in 20261023y):
--     cockpit_name_key(text)                 money.js nameKey in SQL
--     cockpit_billing_card_listed(text,bool) is a card on the pending payments list
--     cockpit_billing_person_name(text)      a name for an email, never the email
--     cockpit_billing_deal_assignments()     every signed deal and its card
--     cockpit_billing_deal_cards()           each card and its newest deal
--     cockpit_billing_deal_rails(text,text)  the payments that count for a deal
--   cockpit_billing_balances_read()          the one read the screen calls:
--                          CEO, client success or finance seat; a success
--                          manager gets only the cards cockpit_client_allowed
--                          lets through and never the deals with no card, the
--                          Back with sales group, untied money or contact names.
--
-- The rule that turns these rows into parts and figures is the pure
-- src/lib/billingBalances.ts in both cockpits; nothing here decides a figure.
-- Safe to run twice: tables and indexes IF NOT EXISTS, functions CREATE OR
-- REPLACE, triggers and the kind check dropped and created again.


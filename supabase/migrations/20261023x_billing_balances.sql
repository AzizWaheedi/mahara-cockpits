CREATE TABLE IF NOT EXISTS public.cockpit_billing_confirmations (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clickup_task_id      text NOT NULL CHECK (clickup_task_id ~ '^[A-Za-z0-9_-]{1,40}$'),
  /** The signed deal (B2B response_id); null only for a card with no terms on record (part 'all'). */
  deal_response_id     text,
  part                 text NOT NULL CHECK (part IN ('deposit', 'onboarding', 'later', 'all')),
  /** 0 for deposit, onboarding and all; k >= 1 for the k-th later part. */
  part_no              smallint NOT NULL DEFAULT 0,
  amount               numeric NOT NULL CHECK (amount > 0 AND amount <= 100000),
  currency             text NOT NULL CHECK (currency IN ('USD', 'KWD')),
  usd                  numeric NOT NULL CHECK (usd > 0),
  /** Rails that arrive on their own. A transfer, cheque or cash is logged as a payment instead. */
  rail                 text NOT NULL CHECK (rail IN ('whop', 'tap', 'ecom')),
  paid_on              date NOT NULL,
  evidence_url         text CHECK (evidence_url IS NULL OR (evidence_url ~ '^https://[^[:space:]<>"'']+$' AND length(evidence_url) <= 1000)),
  note                 text CHECK (note IS NULL OR length(note) <= 500),
  /** What the rails showed for the deal when the person confirmed, and how fresh that was. */
  rails_usd_at_confirm numeric,
  rails_as_of          timestamptz,
  source               text NOT NULL CHECK (source IN ('ceo', 'csm')),
  confirmed_by         text NOT NULL,
  /** From cockpit_is_ceo() on the server, never from the request. */
  confirmed_by_ceo     boolean NOT NULL,
  confirmed_at         timestamptz NOT NULL DEFAULT now(),
  event_id             bigint,
  withdrawn_by         text,
  withdrawn_at         timestamptz,
  withdrawn_reason     text CHECK (withdrawn_reason IS NULL OR length(withdrawn_reason) BETWEEN 3 AND 300),
  CONSTRAINT cockpit_billing_confirmations_part_no CHECK (
    (part = 'later' AND part_no BETWEEN 1 AND 36) OR (part <> 'later' AND part_no = 0)),
  CONSTRAINT cockpit_billing_confirmations_deal_or_all CHECK (deal_response_id IS NOT NULL OR part = 'all'),
  CONSTRAINT cockpit_billing_confirmations_withdrawn_set CHECK (num_nonnulls(withdrawn_by, withdrawn_at, withdrawn_reason) IN (0, 3))
);
COMMENT ON TABLE public.cockpit_billing_confirmations IS
  'A person''s word that a part of a client''s plan was paid on Whop, Tap or an Ecom link (Pending payments, 23 Oct 2026). Never money: not cash, LTV or pay. Proven only by a matching payment on the rail it names. Written only by cockpit_billing_balance_write; withdrawn once, never edited or deleted.';
